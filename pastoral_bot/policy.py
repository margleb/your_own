def system_prompt(mode: Mode, settings=None) -> str:
    idle = getattr(settings, "temporary_idle_seconds", 1800)
    lifetime = getattr(settings, "temporary_max_seconds", 7200)
    limit = getattr(settings, "daily_answer_limit", 10)
    backups = getattr(settings, "backup_retention_days", 7)
    idle_label = "30 минут" if idle == 1800 else f"{idle} секунд"
    lifetime_label = "2 часа" if lifetime == 7200 else f"{lifetime} секунд"
    current_storage = (
        "Текущий режим этой беседы — подготовка к исповеди: текст не сохраняется в обычной истории. "
        if mode == Mode.CONFESSION else
        "Текущий режим этой беседы обычный: сообщения сохраняются в истории. Чтобы начать временную подготовку к исповеди, человеку нужно явно выбрать её через /mode до дальнейшего рассказа. "
    )
    service_facts = (
        current_storage +
        "Хранение определяется выбранным режимом, а не словами сообщения. Упоминание исповеди или просьба не записывать не переключают режим; не утверждай, что текущий разговор временный, если режим обычный. "
        "Проверенные сведения о работе сервиса: обычная история сохраняется в отдельной базе до /delete_history. "
        "Режим подготовки к исповеди не записывает текст в базу, индекс, долговечную очередь или журналы. "
        f"Временный контекст существует в оперативной памяти до {idle_label} бездействия, максимум {lifetime_label}, "
        "и исчезает при перезапуске. После этого режим остаётся временным до явного переключения пользователем. "
        "Telegram сохраняет облачную переписку. Наши запросы передаются через OpenRouter только к провайдерам "
        "с политикой Zero Data Retention; это не обещание полной анонимности. "
        f"Резервные копии обычной истории зашифрованы и хранятся до {backups} дней; удаления повторяются при восстановлении. "
        "Удаление истории бота не удаляет сообщения из Telegram. /new начинает тему, а не удаляет обычную память. "
        f"Сервис бесплатный: до {limit} ответов за московские сутки, общий суточный бюджет модели ограничен. "
        "Бот принимает только текст в личных чатах; у него нет платежей, голосовых сообщений, веб-поиска, "
        "автоматических рассылок и функции пересылки признаний. Человек сам редактирует и сохраняет свою заметку. "
        "Технические журналы содержат только числовые показатели и коды ошибок, без текстов бесед."
    )
    return f"Версия правил: {POLICY_VERSION}\n{SYSTEM_POLICY}\n{MODE_POLICIES[mode]}\n{service_facts}"


